class ReleaseTrack {
  // Pass the entire MusicBrainz recording object into the constructor
  constructor(recordingData) {
    this.title = recordingData.title;

    // Extract artist names from the artist-credit array
    this.artists = recordingData["artist-credit"]?.map((ac) => ac.name) || [];

    // Format duration from milliseconds to MM:SS
    this.duration = this.formatDuration(recordingData.length);

    // Pick the best release (preferring "Official" albums, falling back to the first one)
    this.bestRelease =
      recordingData.releases?.find((r) => r.status === "Official") ||
      recordingData.releases?.[0] ||
      null;

    this.albumTitle = this.bestRelease
      ? this.bestRelease.title
      : "Unknown Album";
    this.releaseId = this.bestRelease ? this.bestRelease.id : null;
    this.releaseGroupId = recordingData["release-group"]?.id || null;

    this.url = `https://musicbrainz.org/recording/${recordingData.id}`;
  }

  // Helper function to turn milliseconds (e.g., 260000) into "4:20"
  formatDuration(ms) {
    if (!ms) return "--:--";
    const minutes = Math.floor(ms / 60000);
    const seconds = Math.floor((ms % 60000) / 1000);
    return `${minutes}:${seconds.toString().padStart(2, "0")}`;
  }

  draw() {
    const recording = document.createElement("a");
    recording.className =
      "text-decoration-none track-item simple-hover d-flex align-items-center justify-content-between p-2 mb-2 bg-body-secondary rounded";
    recording.href = this.url;

    // --- Left Section: Cover Art, Title, and Album ---
    const leftSection = document.createElement("div");
    leftSection.className = "d-flex align-items-center gap-3";

    /* Cover Art Image */
    const img = document.createElement("img");
    img.className = "rounded bg-dark-subtle";
    img.style.cssText = "width: 50px; height: 50px; object-fit: cover;";
    img.src = "https://placehold.co/50x50?text=Loading";

    const loadImage = async () => {
      const tryFetch = async (url) => {
        const res = await fetch(url);
        if (!res.ok) throw new Error();
        return res.json();
      };

      try {
        if (this.releaseId) {
          const data = await tryFetch(
            `https://coverartarchive.org/release/${this.releaseId}`,
          );
          const front = data.images?.find((i) => i.front === true);
          img.src =
            front?.thumbnails["250"] ||
            front?.image ||
            "https://placehold.co/50x50?text=No+Art";
          return;
        }
      } catch (e) {
        // Fallback to release-group
      }

      try {
        if (this.releaseGroupId) {
          const data = await tryFetch(
            `https://coverartarchive.org/release-group/${this.releaseGroupId}`,
          );
          const front = data.images?.find((i) => i.front === true);
          img.src =
            front?.thumbnails["250"] ||
            front?.image ||
            "https://placehold.co/50x50?text=No+Art";
          return;
        }
      } catch (e) {
        // Both failed
      }

      img.src = "https://placehold.co/50x50?text=No+Art";
    };

    const observer = new IntersectionObserver((entries) => {
      if (entries[0].isIntersecting) {
        loadImage();
        observer.unobserve(recording);
      }
    });
    observer.observe(recording);

    /* Text Meta Container */
    const textContainer = document.createElement("div");
    textContainer.className = "d-flex flex-column";

    /* Track Title */
    const title = document.createElement("span");
    title.className = "fw-bold";
    title.textContent = this.title;

    /* Album Name */
    const album = document.createElement("small");
    album.className = "text-muted";
    album.textContent = this.albumTitle;

    textContainer.append(title, album);
    leftSection.append(img, textContainer);

    // --- Right Section: Artists and Duration ---
    const rightSection = document.createElement("div");
    rightSection.className = "d-flex align-items-center gap-3";

    /* Artist Badge List */
    const artistsDiv = document.createElement("div");
    artistsDiv.className = "d-flex flex-wrap gap-1 justify-content-end";

    this.artists.slice(0, 3).forEach((a) => {
      const artistElement = document.createElement("span");
      artistElement.className = "badge text-bg-secondary";
      artistElement.textContent = a;
      artistsDiv.appendChild(artistElement);
    });

    /* Track Duration */
    const durationSpan = document.createElement("span");
    durationSpan.className = "text-muted small font-monospace";
    durationSpan.textContent = this.duration;

    rightSection.append(artistsDiv, durationSpan);

    // Append everything to the main container
    recording.append(leftSection, rightSection);
    return recording;
  }
}
